/**
 * 테스트 하나가 끝날 때마다 이벤트 루프를 한 번 연다.
 *
 * 코어 테스트는 통째로 **동기** 계산이다. vitest 워커는 결과를 메인 프로세스에
 * 알리고(onTaskUpdate) 그 응답을 기다리는데, 응답은 IPC 메시지 = 매크로태스크로
 * 온다. 그런데 러너가 테스트를 `await`로 이어 도는 동안에는 마이크로태스크만
 * 돌기 때문에 파일이 다 끝나기 전에는 그 메시지를 집을 수가 없다. 즉 워커는
 * "보내 놓고 제 손으로 막아 놓은" 상태가 된다.
 *
 * birpc의 응답 대기는 60초 고정이고 설정으로 못 바꾼다. 그래서 무거운 파일
 * (education 103초, project 57초)이 그 선을 넘으면
 *
 *   Error: [vitest-worker]: Timeout calling "onTaskUpdate"
 *
 * 가 처리 안 된 오류로 올라가고, **188개가 전부 통과해도 종료 코드가 1**이 된다.
 * 배포 워크플로가 여기서 막혔다.
 *
 * setTimeout 0은 진짜 매크로태스크 경계라, 여기서 밀린 IPC 메시지가 처리된다.
 * 테스트당 한 번이면 어떤 한 테스트도 60초를 안 넘는 한 안전하다 (가장 긴 것이
 * 40초다). 비용은 테스트당 1틱이다.
 */
import { afterEach } from "vitest";

afterEach(async () => {
  await new Promise((r) => setTimeout(r, 0));
});
